"""Turns "Muslim Vegukin" in Playfair Display Bold into a VectorDrawable
for the home-screen widgets: app fonts don't reach widgets, paths do.

    pip install fonttools
    python3 tool/widget_wordmark.py assets/fonts/PlayfairDisplay-Bold.ttf \
        android/app/src/main/res/drawable/ic_widget_wordmark.xml "Muslim Vegukin" 19
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

font_path, out_path, text, height_dp = sys.argv[1], sys.argv[2], sys.argv[3], float(sys.argv[4])
font = TTFont(font_path)
gs = font.getGlyphSet()
cmap = font.getBestCmap()
hmtx = font['hmtx']
# GPOS kerning is ignored: Playfair's pair kerning is subtle at this size.
x = 0
paths = SVGPathPen(gs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
bounds = BoundsPen(gs)
for ch in text:
    g = cmap[ord(ch)]
    t = (1, 0, 0, -1, x, 0)  # flip y: font y-up, vector y-down
    gs[g].draw(TransformPen(paths, t))
    gs[g].draw(TransformPen(bounds, t))
    x += hmtx[g][0]
xmin, ymin, xmax, ymax = bounds.bounds
w, h = xmax - xmin, ymax - ymin
d = paths.getCommands()
scale = height_dp / h
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- "{text}" in Playfair Display Bold, as paths: widgets can't load app fonts.
     Generated by tool/widget_wordmark.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{w*scale:.2f}dp"
    android:height="{height_dp:g}dp"
    android:viewportWidth="{w:.0f}"
    android:viewportHeight="{h:.0f}">
    <group android:translateX="{-xmin:.0f}" android:translateY="{-ymin:.0f}">
        <path
            android:fillColor="@color/widget_ink"
            android:pathData="{d}" />
    </group>
</vector>
'''
open(out_path, 'w').write(xml)
print(f'{w:.0f}x{h:.0f} units, {w*scale:.1f}x{height_dp}dp, ratio {w/h:.2f}, {len(d)} chars')
