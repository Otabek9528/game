"""Draws the app's emblem into the Android icon and splash files.

The emblem: a gold eight-pointed star (khatam) with an emerald star cut into
it, and in its heart an M whose middle stroke is a gold V: M for Muslim, V
for Vegukin. The same shapes, with the same numbers, are painted in the app
by lib/core/widgets/khatam.dart; change both together.

    pip install pillow numpy
    python3 tool/emblem.py            # from mobile/
    python3 tool/emblem.py store.png  # also a 512 px Play Store icon
"""
import math
import os
import sys

import numpy as np
from PIL import Image, ImageDraw

RES = 'android/app/src/main/res'

# Shapes, in units of the star's half-width (centre to tip).
RING_CUT = 0.76      # the emerald star cut into the gold one
M_WIDTH = 0.69
M_HEIGHT = 0.54
M_STEM = 0.21        # of the M's width
M_FLARE = 1.12       # the V's arms leave the top a little wider than the stems
M_NOTCH = 0.50       # depth of the M's top valley, of its height
M_JOIN = 0.30        # where the V's underside meets the stems, of its height
HEART_STAR = 0.28    # the small star at the heart, on the splash screen

EMERALD900 = '#064E3B'
EMERALD800 = '#065F46'
GOLD300 = '#F7D56B'
GOLD400 = '#EAB932'
GOLD500 = '#D4A21A'
CREAM = '#FFF6E0'

KHATAM = [(8.00, 0.00), (10.34, 2.34), (13.66, 2.34), (13.66, 5.66), (16.00, 8.00), (13.66, 10.34),
          (13.66, 13.66), (10.34, 13.66), (8.00, 16.00), (5.66, 13.66), (2.34, 13.66), (2.34, 10.34),
          (0.00, 8.00), (2.34, 5.66), (2.34, 2.34), (5.66, 2.34)]


def khatam(cx, cy, r, rotation=0.0):
    c, s = math.cos(rotation), math.sin(rotation)
    out = []
    for x, y in KHATAM:
        dx, dy = (x - 8) / 8 * r, (y - 8) / 8 * r
        out.append((cx + dx * c - dy * s, cy + dx * s + dy * c))
    return out


def monogram(cx, cy, r):
    """(left stem, right stem, V) of the M, for a star of half-width r."""
    w, h = M_WIDTH * r, M_HEIGHT * r
    x0, y0 = cx - w / 2, cy - h / 2
    t = M_STEM
    a = M_STEM * M_FLARE

    def p(x, y):
        return x0 + x * w, y0 + y * h

    left = [p(0, 0), p(t, 0), p(t, 1), p(0, 1)]
    right = [p(1 - t, 0), p(1, 0), p(1, 1), p(1 - t, 1)]
    v = [p(t, 0), p(a, 0), p(0.5, M_NOTCH), p(1 - a, 0), p(1 - t, 0), p(1 - t, M_JOIN), p(0.5, 1), p(t, M_JOIN)]
    return left, right, v


# ---------------------------------------------------------------- vectors

def _d(*polygons):
    return ' '.join('M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in poly) + ' Z' for poly in polygons)


def _argb(hex_color):
    return '#FF' + hex_color[1:]


def _path(d, fill, even_odd=False):
    rule = '\n        android:fillType="evenOdd"' if even_odd else ''
    return f'''    <path
        android:fillColor="{fill}"{rule}
        android:pathData="{d}" />'''


def _gold_ring(d, r, c):
    """The ring in the app's gold, light top-left to deep bottom-right."""
    return f'''    <path
        android:fillType="evenOdd"
        android:pathData="{d}">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="{c - r:.2f}" android:startY="{c - r:.2f}"
                android:endX="{c + r:.2f}" android:endY="{c + r:.2f}">
                <item android:offset="0" android:color="{_argb(GOLD300)}" />
                <item android:offset="1" android:color="{_argb(GOLD500)}" />
            </gradient>
        </aapt:attr>
    </path>'''


def _vector(size_dp, comment, body):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/emblem.py: {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
'''


def ring_d(c, r, rotation=0.0):
    return _d(khatam(c, c, r, rotation), khatam(c, c, r * RING_CUT, rotation))


def emblem_vector(r, size_dp, comment):
    c = 54
    left, right, v = monogram(c, c, r)
    body = '\n'.join([
        _gold_ring(ring_d(c, r), r, c),
        _path(_d(left, right), _argb(CREAM)),
        _path(_d(v), _argb(GOLD400)),
    ])
    return _vector(size_dp, comment, body)


def monochrome_vector(r):
    c = 54
    left, right, v = monogram(c, c, r)
    body = '\n'.join([
        _path(ring_d(c, r), '#FFFFFFFF', even_odd=True),
        _path(_d(left, right, v), '#FFFFFFFF'),
    ])
    return _vector(108, 'the emblem in one colour, for Android 13+ themed icons.', body)


def splash_vector(r):
    """The opening's first frame: the star with the small star at its heart.
    The app's opening animation (lib/features/opening) starts from it."""
    c = 54
    body = '\n'.join([
        _gold_ring(ring_d(c, r), r, c),
        _path(_d(khatam(c, c, r * HEART_STAR, math.pi / 8)), _argb(GOLD300)),
    ])
    return _vector(288, 'the splash mark, the first frame of the app\'s opening animation.', body)


# ---------------------------------------------------------------- pictures

def _rgb(hex_color):
    return tuple(int(hex_color[i:i + 2], 16) for i in (1, 3, 5))


def picture(px, star=0.54, square=False):
    """The emblem on emerald, px square: a disc (legacy launcher icons) or the
    whole square (store icon, bot avatars: they round it themselves). star:
    its width, of the picture's."""
    k = 8
    n = px * k
    im = Image.new('RGBA', (n, n), (0, 0, 0, 0))
    if square:
        im.paste(_rgb(EMERALD800), (0, 0, n, n))
    else:
        ImageDraw.Draw(im).ellipse([0, 0, n - 1, n - 1], fill=_rgb(EMERALD800))
    c, r = n / 2, n * star / 2

    # Gold ring, with the same diagonal light as in the app.
    yy, xx = np.mgrid[0:n, 0:n]
    t = np.clip(((xx - (c - r)) + (yy - (c - r))) / (4 * r), 0, 1)[..., None]
    g0, g1 = np.array(_rgb(GOLD300)), np.array(_rgb(GOLD500))
    rgb = (g0 + (g1 - g0) * t).round().astype(np.uint8)
    ramp = Image.fromarray(np.dstack([rgb, np.full((n, n, 1), 255, np.uint8)]), 'RGBA')
    mask = Image.new('L', (n, n), 0)
    md = ImageDraw.Draw(mask)
    md.polygon(khatam(c, c, r), fill=255)
    md.polygon(khatam(c, c, r * RING_CUT), fill=0)
    im.paste(ramp, (0, 0), mask)

    d = ImageDraw.Draw(im)
    left, right, v = monogram(c, c, r)
    d.polygon(left, fill=_rgb(CREAM))
    d.polygon(right, fill=_rgb(CREAM))
    d.polygon(v, fill=_rgb(GOLD400))
    return im.resize((px, px), Image.LANCZOS)


def write(path, text):
    with open(path, 'w') as f:
        f.write(text)
    print('wrote', path)


def main():
    write(f'{RES}/drawable/ic_launcher_foreground.xml',
          emblem_vector(29, 108, 'the emblem, the launcher icon\'s foreground.'))
    write(f'{RES}/drawable/ic_launcher_monochrome.xml', monochrome_vector(29))
    write(f'{RES}/drawable/ic_splash_mark.xml', splash_vector(29))
    for folder, px in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)):
        path = f'{RES}/mipmap-{folder}/ic_launcher.png'
        picture(px).save(path, optimize=True)
        print('wrote', path)
    if len(sys.argv) > 1:
        picture(512, star=0.56, square=True).save(sys.argv[1], optimize=True)
        print('wrote', sys.argv[1])


if __name__ == '__main__':
    os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    main()
