"""Writes lib/features/account/privacy_text.dart from store/privacy.html.

The privacy policy lives twice: on the web (privacy.html, which Google Play
links) and in the app (the native page). The HTML is the one to edit; run this
after, from mobile/:

    python3 tool/privacy_text.py

test/privacy_test.dart fails while the two differ.
"""

import html.parser
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'store' / 'privacy.html'
TARGET = ROOT / 'lib' / 'features' / 'account' / 'privacy_text.dart'
LANGUAGES = ('uz', 'en', 'ru')


class Policy(html.parser.HTMLParser):
    """Each <section id=…> as lines: '# ' title, '_ ' date, '## ' heading,
    '- ' list item, '[box]' … '[/box]', else a paragraph; **bold** and
    [text](link) inside."""

    def __init__(self):
        super().__init__()
        self.sections = {}
        self.lines = None
        self.text = None
        self.prefix = ''
        self.href = None

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == 'section':
            self.lines = self.sections.setdefault(attrs['id'], [])
        elif self.lines is None:
            return
        elif tag == 'div' and 'box' in attrs.get('class', ''):
            self.lines.append('[box]')
        elif tag in ('h1', 'h2', 'p', 'li'):
            self.text = []
            self.prefix = {'h1': '# ', 'h2': '## ', 'li': '- '}.get(tag, '')
            if tag == 'p' and attrs.get('class') == 'date':
                self.prefix = '_ '
        elif tag == 'b' and self.text is not None:
            self.text.append('**')
        elif tag == 'a' and self.text is not None:
            self.href = attrs['href']
            self.text.append('[')

    def handle_endtag(self, tag):
        if self.lines is None:
            return
        if tag == 'section':
            self.lines = None
        elif tag == 'div':
            self.lines.append('[/box]')
        elif tag in ('h1', 'h2', 'p', 'li') and self.text is not None:
            self.lines.append(self.prefix + re.sub(r'\s+', ' ', ''.join(self.text)).strip())
            self.text = None
        elif tag == 'b' and self.text is not None:
            self.text.append('**')
        elif tag == 'a' and self.text is not None:
            self.text.append(f']({self.href})')

    def handle_data(self, data):
        if self.text is not None:
            self.text.append(data)


def dart_string(text):
    escaped = text.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
    return f"'{escaped}'"


def main():
    policy = Policy()
    policy.feed(SOURCE.read_text(encoding='utf-8'))
    out = [
        '// Generated by tool/privacy_text.py from store/privacy.html: edit that,',
        '// then run the tool. test/privacy_test.dart checks the two agree.',
        '',
        '/// The privacy policy by language, a line per block: "# " title, "_ "',
        '/// date, "## " heading, "- " list item, "[box]" … "[/box]" around the',
        '/// account-deletion part, else a paragraph; **bold** and [text](link)',
        '/// inside.',
        'const privacyText = <String, List<String>>{',
    ]
    for language in LANGUAGES:
        out.append(f"  '{language}': [")
        for line in policy.sections[language]:
            out.append(f'    {dart_string(line)},')
        out.append('  ],')
    out.append('};')
    TARGET.write_text('\n'.join(out) + '\n', encoding='utf-8')
    print(f'{TARGET.relative_to(ROOT)}: {", ".join(f"{k} {len(policy.sections[k])}" for k in LANGUAGES)} blocks')


if __name__ == '__main__':
    main()
